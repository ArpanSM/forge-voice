"""Deterministic corpus generation for tenants, seeds, scenarios and hashes."""

from __future__ import annotations

import hashlib
import json
import shutil
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import yaml

from forge_voice.corpus.seed import ANCHOR_DATE, build_tenant_seed
from forge_voice.scenarios import AudioScenario, ScenarioManifest, TextScenario, load_manifest
from forge_voice.tenants import load_all_tenants


@dataclass(frozen=True)
class CorpusSummary:
    output_dir: Path
    artifacts: dict[str, str]
    manifest_sha256: str
    text_scenarios: int
    audio_scenarios: int


def _json_bytes(value: Any) -> bytes:
    return (json.dumps(value, indent=2, sort_keys=True, ensure_ascii=True) + "\n").encode()


def _yaml_bytes(value: Any) -> bytes:
    return yaml.safe_dump(value, sort_keys=True, allow_unicode=True).encode()


def _caller_script(scenario: TextScenario) -> bytes:
    lines = [
        f"# scenario: {scenario.id}",
        f"# persona: {scenario.persona}",
        f"# goal: {scenario.goal}",
        f"# max_turns: {scenario.max_turns}",
        "",
        *scenario.turns,
        "",
    ]
    return "\n".join(lines).encode()


def _audio_placeholder(scenario: AudioScenario) -> bytes:
    return _yaml_bytes(
        {
            "scenario_id": scenario.id,
            "method": scenario.audio.method,
            "fixture": scenario.audio.fixture,
            "status": "placeholder",
            "note": "Audio is generated by the transport ticket (#5); this file is a marker.",
        }
    )


def _audio_fixture_marker(scenario: AudioScenario) -> bytes:
    return _yaml_bytes(
        {
            "scenario_id": scenario.id,
            "method": scenario.audio.method,
            "fixture": scenario.audio.fixture,
            "status": "placeholder",
            "note": "Not an audio file. Ticket #5 generates the real fixture.",
        }
    )


def _artifacts(root: Path, manifest: ScenarioManifest) -> tuple[dict[str, bytes], str]:
    artifacts: dict[str, bytes] = {}
    for slug in sorted(manifest.tenants):
        artifacts[f"tenants/{slug}.yaml"] = (root / "tenants" / f"{slug}.yaml").read_bytes()

    manifest_bytes = (root / "scenarios" / "manifest.yaml").read_bytes()
    artifacts["scenarios/manifest.yaml"] = manifest_bytes

    for scenario in manifest.text_scenarios:
        artifacts[f"scenarios/callers/{scenario.id}.txt"] = _caller_script(scenario)
    for scenario in manifest.audio_scenarios:
        artifacts[f"scenarios/audio/{scenario.id}.placeholder.yaml"] = _audio_placeholder(scenario)
        artifacts[f"scenarios/{scenario.audio.fixture}.placeholder"] = _audio_fixture_marker(
            scenario
        )

    for slug, tenant in sorted(load_all_tenants(root / "tenants").items()):
        seed = build_tenant_seed(tenant)
        artifacts[f"seed/{slug}.json"] = _json_bytes(seed.model_dump(mode="json"))

    return artifacts, hashlib.sha256(manifest_bytes).hexdigest()


def generate_corpus(root: Path | str) -> CorpusSummary:
    """Regenerate `fixtures/corpus/` from the tenant and scenario sources.

    Inputs are validated before any output path is touched. Output uses sorted JSON/YAML and
    a fixed anchor date, so two runs produce identical bytes and hashes.
    """
    root = Path(root).resolve()
    tenants = load_all_tenants(root / "tenants")
    manifest = load_manifest(
        root / "scenarios" / "manifest.yaml",
        known_tenants=tenants.keys(),
    )
    artifacts, manifest_sha256 = _artifacts(root, manifest)

    hashes = {
        "schema_version": 1,
        "generator": "forge_voice.corpus",
        "anchor_date": ANCHOR_DATE.isoformat(),
        "manifest_id": manifest.manifest_id,
        "counts": manifest.counts.model_dump(),
        "artifacts": [
            {
                "path": relative_path,
                "sha256": hashlib.sha256(content).hexdigest(),
            }
            for relative_path, content in sorted(artifacts.items())
        ],
    }

    fixtures_dir = root / "fixtures"
    staging = fixtures_dir / ".corpus.staging"
    output = fixtures_dir / "corpus"
    shutil.rmtree(staging, ignore_errors=True)
    staging.mkdir(parents=True)
    try:
        for relative_path, content in sorted(artifacts.items()):
            target = staging / relative_path
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(content)
        (staging / "hashes.json").write_bytes(_json_bytes(hashes))
        shutil.rmtree(output, ignore_errors=True)
        staging.replace(output)
    finally:
        shutil.rmtree(staging, ignore_errors=True)

    digest_by_path = {entry["path"]: entry["sha256"] for entry in hashes["artifacts"]}
    return CorpusSummary(
        output_dir=output,
        artifacts=digest_by_path,
        manifest_sha256=manifest_sha256,
        text_scenarios=manifest.counts.text,
        audio_scenarios=manifest.counts.audio,
    )
