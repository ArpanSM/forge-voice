"""Pydantic schema for the evaluation scenario manifest.

The manifest is the source of truth for the 40 text + 10 audio set. The loader enforces the
locked counts, dev/held-out/smoke splits, critical repeats, hard-gate labels and required
fields from roadmap #26.
"""

from __future__ import annotations

from datetime import date
from typing import Annotated, Any, Literal

from pydantic import Field, field_validator, model_validator

from forge_voice.models import StrictModel, ensure_unique

Identifier = Annotated[str, Field(pattern=r"^[a-z][a-z0-9_]*$")]


HARD_GATES = frozenset(
    {
        "double_booking",
        "slot_correctness",
        "confirmation_accuracy",
        "emergency_triage",
        "handoff_correctness",
        "audit_completeness",
        "unsafe_promises",
        "cross_tenant",
        "unauthorized_write",
    }
)

TOOLS = frozenset(
    {
        "lookup_customer",
        "get_service_area",
        "get_availability",
        "book_appointment",
        "reschedule_appointment",
        "cancel_appointment",
        "create_emergency_ticket",
        "transfer_to_human",
    }
)

OUTCOMES = frozenset(
    {
        "booked",
        "rescheduled",
        "cancelled",
        "emergency_ticket",
        "transferred",
        "callback",
        "info_only",
        "abandoned",
        "failed",
        "booked_or_transferred",
        "booked_or_callback",
    }
)

CRITICAL_REPEAT_IDS = frozenset(
    {
        "text_book_01",
        "text_reschedule_01",
        "text_cancel_01",
        "text_noavail_01",
        "text_emergency_01",
        "text_confirm_refusal_01",
        "text_timeout_01",
        "text_duplicate_01",
        "text_injection_01",
        "text_afterhours_01",
    }
)

LOCKED_COUNTS = {
    "text": 40,
    "text_dev": 32,
    "text_held_out": 8,
    "text_smoke": 8,
    "text_critical_repeat": 10,
    "audio": 10,
    "audio_dev": 8,
    "audio_held_out": 2,
    "audio_smoke": 2,
    "audio_local": 6,
}


class ManifestCounts(StrictModel):
    text: int = Field(ge=0)
    text_dev: int = Field(ge=0)
    text_held_out: int = Field(ge=0)
    text_smoke: int = Field(ge=0)
    text_critical_repeat: int = Field(ge=0)
    audio: int = Field(ge=0)
    audio_dev: int = Field(ge=0)
    audio_held_out: int = Field(ge=0)
    audio_smoke: int = Field(ge=0)
    audio_local: int = Field(ge=0)


LOCKED_COUNTS = ManifestCounts(
    text=40,
    text_dev=32,
    text_held_out=8,
    text_smoke=8,
    text_critical_repeat=10,
    audio=10,
    audio_dev=8,
    audio_held_out=2,
    audio_smoke=2,
    audio_local=6,
)


class ScenarioBase(StrictModel):
    id: Identifier
    mode: Literal["text", "audio"]
    category: Identifier
    tenant: Identifier
    held_out: bool
    smoke: bool
    critical_repeat: bool
    persona: str = Field(min_length=1)
    goal: str = Field(min_length=1)
    expected_tool_calls: list[Identifier]
    expected_final_state: dict[str, Any] = Field(min_length=1)
    pass_condition: str = Field(min_length=1)
    hard_gates: list[str] = Field(min_length=1)
    max_turns: int = Field(gt=0, le=20)

    @field_validator("hard_gates")
    @classmethod
    def known_hard_gates(cls, gates: list[str]) -> list[str]:
        unknown = set(gates) - HARD_GATES
        if unknown:
            raise ValueError(f"unknown hard_gate labels: {sorted(unknown)}")
        ensure_unique(gates, "hard_gate labels")
        return gates

    @field_validator("expected_tool_calls")
    @classmethod
    def known_tools(cls, tools: list[str]) -> list[str]:
        unknown = set(tools) - TOOLS
        if unknown:
            raise ValueError(f"unknown tool names: {sorted(unknown)}")
        ensure_unique(tools, "expected tool call names")
        return tools

    @field_validator("expected_final_state")
    @classmethod
    def outcome_is_known(cls, state: dict[str, Any]) -> dict[str, Any]:
        outcome = state.get("outcome")
        if outcome not in OUTCOMES:
            raise ValueError(f"expected_final_state.outcome must be one of {sorted(OUTCOMES)}")
        return state


class TextScenario(ScenarioBase):
    mode: Literal["text"]
    turns: list[str] = Field(min_length=1, max_length=30)

    @field_validator("turns")
    @classmethod
    def turns_not_blank(cls, turns: list[str]) -> list[str]:
        if any(not turn.strip() for turn in turns):
            raise ValueError("turns must not contain blank caller utterances")
        return turns


class AudioFixture(StrictModel):
    method: Literal["livekit_simulation", "degraded_clip"]
    fixture: str = Field(min_length=1)

    @field_validator("fixture")
    @classmethod
    def fixture_is_safe_placeholder_path(cls, fixture: str) -> str:
        if not fixture.startswith("fixtures/audio/") or not fixture.endswith(".wav"):
            raise ValueError(
                "audio.fixture must be a relative fixtures/audio/*.wav path; "
                "audio is generated by the transport ticket"
            )
        if ".." in fixture or fixture.startswith("/"):
            raise ValueError("audio.fixture must not escape the scenarios directory")
        return fixture


class AudioScenario(ScenarioBase):
    mode: Literal["audio"]
    audio: AudioFixture
    local_subset: bool


Scenario = Annotated[TextScenario | AudioScenario, Field(discriminator="mode")]


class ScenarioManifest(StrictModel):
    schema_version: Literal[1]
    manifest_id: Annotated[str, Field(pattern=r"^[a-z][a-z0-9_-]*$")]
    generated: date
    tenants: list[Identifier] = Field(min_length=1)
    counts: ManifestCounts
    scenarios: list[Scenario] = Field(min_length=1)

    @model_validator(mode="after")
    def validate_manifest(self) -> ScenarioManifest:
        text = [scenario for scenario in self.scenarios if scenario.mode == "text"]
        audio = [scenario for scenario in self.scenarios if scenario.mode == "audio"]

        ids = [scenario.id for scenario in self.scenarios]
        ensure_unique(ids, "scenario id(s)")

        for scenario in self.scenarios:
            if not scenario.id.startswith(f"{scenario.mode}_"):
                raise ValueError(f"scenario id {scenario.id!r} must start with {scenario.mode}_")

        ensure_unique(self.tenants, "manifest tenants")
        manifest_tenants = set(self.tenants)
        scenario_tenants = {scenario.tenant for scenario in self.scenarios}
        if scenario_tenants != manifest_tenants:
            raise ValueError(
                "scenario tenants must match the manifest tenants; "
                f"manifest={sorted(manifest_tenants)}, scenarios={sorted(scenario_tenants)}"
            )

        for scenario in self.scenarios:
            if scenario.smoke and scenario.held_out:
                raise ValueError(
                    f"held-out scenario {scenario.id!r} must not be in the smoke split"
                )

        critical = [scenario.id for scenario in text if scenario.critical_repeat]
        if (
            len(critical) != LOCKED_COUNTS.text_critical_repeat
            or set(critical) != CRITICAL_REPEAT_IDS
        ):
            raise ValueError(
                "critical repeat set must match the locked ten text scenarios; "
                f"expected={sorted(CRITICAL_REPEAT_IDS)}, found={sorted(critical)}"
            )
        if any(scenario.critical_repeat for scenario in audio):
            raise ValueError("critical_repeat is only defined for text scenarios")
        if any(
            scenario.held_out and not scenario.expected_final_state for scenario in self.scenarios
        ):
            raise ValueError("held-out scenarios must carry an expected final state")

        derived = {
            "text": len(text),
            "text_dev": sum(not scenario.held_out for scenario in text),
            "text_held_out": sum(scenario.held_out for scenario in text),
            "text_smoke": sum(scenario.smoke for scenario in text),
            "text_critical_repeat": len(critical),
            "audio": len(audio),
            "audio_dev": sum(not scenario.held_out for scenario in audio),
            "audio_held_out": sum(scenario.held_out for scenario in audio),
            "audio_smoke": sum(scenario.smoke for scenario in audio),
            "audio_local": sum(scenario.local_subset for scenario in audio),
        }
        expected = self.counts.model_dump()
        locked = LOCKED_COUNTS.model_dump()
        locked_mismatches = {
            key: (locked[key], actual) for key, actual in derived.items() if locked[key] != actual
        }
        if locked_mismatches:
            detail = ", ".join(
                f"{key}: locked={locked_value}, found={actual}"
                for key, (locked_value, actual) in sorted(locked_mismatches.items())
            )
            raise ValueError(f"scenarios violate the locked counts: {detail}")

        declared_mismatches = {
            key: (locked_value, expected[key])
            for key, locked_value in locked.items()
            if expected[key] != locked_value
        }
        if declared_mismatches:
            detail = ", ".join(
                f"{key}: locked={locked_value}, declared={declared}"
                for key, (locked_value, declared) in sorted(declared_mismatches.items())
            )
            raise ValueError(f"manifest counts block violates the locked counts: {detail}")

        return self

    @property
    def text_scenarios(self) -> list[TextScenario]:
        return [scenario for scenario in self.scenarios if isinstance(scenario, TextScenario)]

    @property
    def audio_scenarios(self) -> list[AudioScenario]:
        return [scenario for scenario in self.scenarios if isinstance(scenario, AudioScenario)]
