#!/usr/bin/env bash
# Prepare a local .env.local for the demo without printing the secret.
# Fills missing keys and generates a random LiveKit dev secret when empty.
set -euo pipefail

ROOT="${1:-$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)}"
FILE="$ROOT/.env.local"
umask 077

# shellcheck source=scripts/python_bin.sh
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "$SCRIPT_DIR/python_bin.sh"
PYTHON_BIN="$(find_python_bin)" || exit 1

new_secret() {
  "$PYTHON_BIN" -c 'import secrets; print(secrets.token_hex(32))'
}

if [[ ! -f "$FILE" ]]; then
  cat > "$FILE" <<EOF
# Generated by scripts/prepare_local_env.sh. Gitignored; local development only.
LIVEKIT_URL=ws://localhost:7880
LIVEKIT_API_KEY=devkey
LIVEKIT_API_SECRET=$(new_secret)
FORGE_VOICE_PROFILE=local
EOF
  chmod 0600 "$FILE"
  exit 0
fi

ensure_line() {
  local key="$1" value="$2"
  if grep -q "^${key}=" "$FILE"; then
    local current
    current="$(grep "^${key}=" "$FILE" | head -1 | cut -d= -f2-)"
    current="${current//[[:space:]]/}"
    if [[ -z "$current" ]]; then
      FORGE_ENV_KEY="$key" FORGE_ENV_VALUE="$value" "$PYTHON_BIN" - "$FILE" <<'PY'
import os
import sys
from pathlib import Path

path = Path(sys.argv[1])
key = os.environ["FORGE_ENV_KEY"]
value = os.environ["FORGE_ENV_VALUE"]
lines = path.read_text(encoding="utf-8").splitlines()
path.write_text(
    "\n".join(f"{key}={value}" if line.startswith(f"{key}=") else line for line in lines) + "\n",
    encoding="utf-8",
)
PY
    fi
  else
    printf '%s=%s\n' "$key" "$value" >> "$FILE"
  fi
}

ensure_line LIVEKIT_URL "ws://localhost:7880"
ensure_line LIVEKIT_API_KEY "devkey"
ensure_line LIVEKIT_API_SECRET "$(new_secret)"
chmod 0600 "$FILE"
